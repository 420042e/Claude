  Objeto      : [api].[TARJETA_Add]
  Descripción : Alta de una tarjeta.
  Autor       : Equipo Tarjetas
  Fecha       : 2026-09-22
*/
CREATE OR ALTER PROCEDURE [api].[TARJETA_Add]
    @NUMERO_TARJETA_VC      VARCHAR(16),
    @NOMBRE_TITULAR_VC      VARCHAR(100),
    @TIPO_TARJETA_VC        VARCHAR(10),
    @LIMITE_CREDITO_DC      DECIMAL(18,2),
    @FECHA_VENCIMIENTO_DT   DATETIME,
    @USUARIO_CREACION_VC    VARCHAR(50),
    @TARJETA_ID_IN          INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO [api].[TARJETA]
        (NUMERO_TARJETA_VC, NOMBRE_TITULAR_VC, TIPO_TARJETA_VC, LIMITE_CREDITO_DC,
         FECHA_VENCIMIENTO_DT, USUARIO_CREACION_VC)
    VALUES
        (@NUMERO_TARJETA_VC, @NOMBRE_TITULAR_VC, @TIPO_TARJETA_VC, @LIMITE_CREDITO_DC,
         @FECHA_VENCIMIENTO_DT, @USUARIO_CREACION_VC);

    SET @TARJETA_ID_IN = SCOPE_IDENTITY();
END
GO
