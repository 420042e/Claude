IF OBJECT_ID('api.TARJETA', 'U') IS NULL
BEGIN
    CREATE TABLE [api].[TARJETA]
    (
        TARJETA_ID_IN              INT            IDENTITY(1,1) NOT NULL,
        NUMERO_TARJETA_VC          VARCHAR(16)    NOT NULL,
        NOMBRE_TITULAR_VC          VARCHAR(100)   NOT NULL,
        TIPO_TARJETA_VC            VARCHAR(10)    NOT NULL,
        LIMITE_CREDITO_DC          DECIMAL(18,2)  NOT NULL CONSTRAINT DF_TARJETA_LIMITE_CREDITO_DC DEFAULT (0),
        SALDO_DC                   DECIMAL(18,2)  NOT NULL CONSTRAINT DF_TARJETA_SALDO_DC DEFAULT (0),
        FECHA_VENCIMIENTO_DT       DATETIME       NOT NULL,
        ESTADO_BT                  BIT            NOT NULL CONSTRAINT DF_TARJETA_ESTADO_BT DEFAULT (1),
        USUARIO_CREACION_VC        VARCHAR(50)    NOT NULL,
        FECHA_CREACION_DT          DATETIME       NOT NULL CONSTRAINT DF_TARJETA_FECHA_CREACION_DT DEFAULT (GETDATE()),
        USUARIO_MODIFICACION_VC    VARCHAR(50)    NULL,
        FECHA_MODIFICACION_DT      DATETIME       NULL,
        CONSTRAINT PK_TARJETA PRIMARY KEY CLUSTERED (TARJETA_ID_IN),
        CONSTRAINT UQ_TARJETA_NUMERO_TARJETA_VC UNIQUE (NUMERO_TARJETA_VC)
    );
END
GO
